const RADIO_TIERRA = 6371;
function km(a: { lat: number; lon: number }, b: { lat: number; lon: number }) {
  const r = Math.PI / 180;
  const x =
    Math.sin(((b.lat - a.lat) * r) / 2) ** 2 +
    Math.cos(a.lat * r) * Math.cos(b.lat * r) * Math.sin(((b.lon - a.lon) * r) / 2) ** 2;
  return 2 * RADIO_TIERRA * Math.asin(Math.sqrt(x));
}

const especie = (c: string) => c.split(" ").slice(0, 2).join(" ");

/** Hides y salidas a menos de `maxKm` del punto, más cerca antes. */
export function hidesCerca(lat: number, lon: number, maxKm = 60): (Hide & { km: number })[] {
  return HIDES.map((h) => ({ ...h, km: Math.round(km({ lat, lon }, h)) }))
    .filter((h) => h.km <= maxKm)
    .sort((a, b) => a.km - b.km);
}

/** Hides y salidas para una especie (por nombre científico). */
export function hidesDe(cientifico: string | null | undefined): Hide[] {
  if (!cientifico) return [];
  const sp = especie(cientifico);
  return HIDES.filter((h) => h.especies.some((e) => especie(e.c) === sp));
}

